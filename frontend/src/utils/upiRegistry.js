export const POPULAR_UPI_APPS = UPI_APP_REGISTRY.filter((app) => app.isPopular)
export const TPAP_UPI_APPS = UPI_APP_REGISTRY.filter((app) => app.category === 'popular' || app.category === 'tpap')
export const BANK_UPI_APPS = UPI_APP_REGISTRY.filter((app) => app.category === 'bank')

/**
 * Searches the registry by app name, entity name, or ID.
 */
export function searchUpiApps(query, categoryFilter = 'all') {
  const q = (query || '').trim().toLowerCase()
  
  return UPI_APP_REGISTRY.filter((app) => {
    // Category match
    if (categoryFilter === 'popular' && !app.isPopular) return false
    if (categoryFilter === 'tpap' && app.category === 'bank') return false
    if (categoryFilter === 'bank' && app.category !== 'bank') return false

    // Query match
    if (!q) return true
    return (
      app.name.toLowerCase().includes(q) ||
      app.entityName.toLowerCase().includes(q) ||
      app.id.toLowerCase().includes(q)
    )
  })
}

/**
 * Retrieves single app metadata by ID.
 */
export function getUpiAppById(id) {
  if (!id) return null
  return UPI_APP_REGISTRY.find((app) => app.id === id) || null
}

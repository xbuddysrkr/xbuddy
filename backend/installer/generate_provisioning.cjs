const fs = require('fs')
const path = require('path')

// For secure public distributions, never bake universal server secrets into the binary.
// Per-station credentials are used, or generated locally on installation if none is configured.
const customKey = process.env.BUILD_STATION_KEY ? process.env.BUILD_STATION_KEY.trim() : ''

let provCsContent = `// Auto-generated by generate_provisioning.cjs during build - Secure per-station provisioning
namespace XBuddyPrintStation
{
    internal static class Provisioning
    {
        public static string GetAgentSecretKey()
        {
            return ""; // Universal master key never embedded in public distributable
        }
    }
}
`

if (customKey && customKey.length >= 32) {
  const salt = [0x5A, 0x3C, 0x7E, 0x1F, 0x4B, 0x6D, 0x2A, 0x8C]
  const keyBytes = Buffer.from(customKey, 'utf8')
  const obfuscated = []
  for (let i = 0; i < keyBytes.length; i++) {
    obfuscated.push('0x' + (keyBytes[i] ^ salt[i % salt.length]).toString(16).padStart(2, '0'))
  }

  provCsContent = `// Auto-generated by generate_provisioning.cjs during custom station build
namespace XBuddyPrintStation
{
    internal static class Provisioning
    {
        private static readonly byte[] Salt = new byte[] { 0x5a, 0x3c, 0x7e, 0x1f, 0x4b, 0x6d, 0x2a, 0x8c };
        private static readonly byte[] ObfuscatedKey = new byte[] {
            ${obfuscated.join(', ')}
        };

        public static string GetAgentSecretKey()
        {
            byte[] decrypted = new byte[ObfuscatedKey.Length];
            for (int i = 0; i < ObfuscatedKey.Length; i++)
            {
                decrypted[i] = (byte)(ObfuscatedKey[i] ^ Salt[i % Salt.Length]);
            }
            return System.Text.Encoding.UTF8.GetString(decrypted);
        }
    }
}
`
}

const outPath = path.join(__dirname, 'Provisioning.cs')
fs.writeFileSync(outPath, provCsContent, 'utf8')
console.log(`[PROVISIONING] Generated ${outPath} (Custom key embedded: ${Boolean(customKey)})`)
